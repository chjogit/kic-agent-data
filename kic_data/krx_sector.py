# KSIC 만으로는 KRX 와 달라지는 대표 사례 (KRX 업종 기준으로 고침)
OVERRIDES: dict[str, str] = {
    "095340": "전기·전자",  # ISC: 반도체 테스트 소켓 제조인데 DART KSIC 가 도매업이라 '유통'으로 들어감
}


def ksic_to_krx(ksic: str | None, ticker: str | None = None) -> str | None:
    if ticker and ticker in OVERRIDES:
        return OVERRIDES[ticker]
    code = "".join(ch for ch in (ksic or "") if ch.isdigit())
    if len(code) < 2:
        return None
    for n in range(len(code), 1, -1):
        hit = _PREFIX.get(code[:n])
        if hit:
            return hit
    return "기타제조" if "10" <= code[:2] <= "34" else "일반서비스"
